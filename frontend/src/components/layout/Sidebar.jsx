const getIcon = (iconName) => {
  switch (iconName) {
    case '📊': return <DashboardIcon />;
    case '🏆': return <TrophyIcon />;
    case '📅': return <CalendarIcon />;
    case '📋': return <DocumentIcon />;
    case '👥': return <UsersIcon />;
    default: return <DashboardIcon />;
  }
};

const Sidebar = ({ isOpen, currentPage, navigateToPage, onLogout }) => {
  const handleNavigation = (page) => {
    if (navigateToPage) {
      navigateToPage(page);
    }
  };

  return (
    <div className={`w-64 bg-green-700 text-white flex flex-col transition-all duration-300 ${
      isOpen ? 'translate-x-0' : '-translate-x-full'
    } fixed top-16 left-0 h-full z-40`}>
      {/* Navigation Menu */}
      <nav className="flex-1 p-4">
        <ul className="space-y-2">
          {navigationItems.map((item) => (
            <li key={item.id}>
              <button
                onClick={() => handleNavigation(item.id)}
                className={`flex items-center gap-3 px-4 py-3 rounded-lg transition-all duration-200 ease-in-out w-full text-left ${
                  currentPage === item.id 
                    ? 'bg-white text-green-700' 
                    : 'bg-green-600 text-white hover:bg-green-500'
                }`}
              >
                <span className={`w-5 h-5 transition-colors duration-200 ${
                  currentPage === item.id ? 'text-green-700' : 'text-white'
                }`}>
                  {getIcon(item.icon)}
                </span>
                <span className={`font-medium transition-colors duration-200 ${
                  currentPage === item.id ? 'text-green-700' : 'text-white'
                }`}>
                  {item.label}
                </span>
              </button>
            </li>
          ))}
        </ul>
      </nav>
    </div>
  );
};

export default Sidebar;
